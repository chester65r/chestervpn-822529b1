package com.example.advancedtunnel.vpn

import android.net.VpnService
import android.util.Log
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.FilterOutputStream
import java.io.InputStream
import java.io.OutputStream
import java.net.InetSocketAddress
import java.net.Socket
import java.nio.charset.StandardCharsets
import javax.net.ssl.SNIHostName
import javax.net.ssl.SSLParameters
import javax.net.ssl.SSLSocket
import javax.net.ssl.SSLSocketFactory

object AdvancedTunnelCoreEngine {
    private const val TAG = "AdvancedTunnelCoreEngine"

    data class TunnelProfile(
        val remoteIp: String,
        val remotePort: Int,
        val targetSni: String,
        val carrierPreset: String, // "stc", "mobily", or "custom"
        val customPayloadTemplate: String,
        val fragmentChunkSize: Int = 6,
        val fragmentJitterMs: Long = 12L
    )

    /**
     * Custom OutputStream wrapper that intercepts the actual TLS ClientHello bytes
     * generated by SSLSocket.startHandshake() and splits them into micro-chunks on the wire.
     */
    private class FragmentedOutputStream(
        out: OutputStream,
        private val chunkSize: Int,
        private val jitterMs: Long
    ) : FilterOutputStream(out) {
        @Volatile
        var fragmentationActive: Boolean = true

        override fun write(b: ByteArray, off: Int, len: Int) {
            if (!fragmentationActive || chunkSize <= 0) {
                out.write(b, off, len)
                out.flush()
                return
            }

            var currentOffset = off
            val endOffset = off + len
            while (currentOffset < endOffset) {
                val sliceLength = minOf(chunkSize, endOffset - currentOffset)
                out.write(b, currentOffset, sliceLength)
                out.flush()
                currentOffset += sliceLength
                if (jitterMs > 0 && currentOffset < endOffset) {
                    Thread.sleep(jitterMs)
                }
            }
        }
    }

    /**
     * Custom Socket wrapper that forces SSLSocket to route its handshake through FragmentedOutputStream.
     */
    private class FragmentingSocketWrapper(
        private val delegate: Socket,
        chunkSize: Int,
        jitterMs: Long
    ) : Socket() {
        val fragmentedOut = FragmentedOutputStream(delegate.getOutputStream(), chunkSize, jitterMs)

        override fun getOutputStream(): OutputStream = fragmentedOut
        override fun getInputStream(): InputStream = delegate.getInputStream()
        override fun isConnected(): Boolean = delegate.isConnected
        override fun isClosed(): Boolean = delegate.isClosed
        override fun close() = delegate.close()
    }

    fun buildPayload(profile: TunnelProfile): String {
        val defaultTemplate = when (profile.carrierPreset.lowercase()) {
            "stc" -> "GET http://[host]/ HTTP/1.1[crlf]Host: [host][crlf]X-Online-Host: [host][crlf]Connection: Upgrade[crlf]Upgrade: websocket[crlf][crlf]"
            "mobily" -> "CONNECT [host_port] HTTP/1.1[crlf]Host: [host][crlf]Proxy-Connection: Keep-Alive[crlf]Connection: Keep-Alive[crlf][crlf]"
            else -> "GET / HTTP/1.1[crlf]Host: [host][crlf]Connection: Upgrade[crlf]Upgrade: websocket[crlf][crlf]"
        }

        val activeTemplate = profile.customPayloadTemplate.ifBlank { defaultTemplate }

        val parsed = activeTemplate
            .replace("[host]", profile.targetSni, ignoreCase = true)
            .replace("[host_port]", "${profile.targetSni}:${profile.remotePort}", ignoreCase = true)
            .replace("[crlf]", "\r\n", ignoreCase = true)
            .replace("\\r\\n", "\r\n")

        return if (!parsed.endsWith("\r\n\r\n")) {
            if (parsed.endsWith("\r\n")) "$parsed\r\n" else "$parsed\r\n\r\n"
        } else {
            parsed
        }
    }

    /**
     * Establishes a tunnel with REAL wire-level TLS ClientHello fragmentation:
     * 1. Opens raw TCP connection (and optionally protects the socket with VpnService).
     * 2. Wraps the raw socket in FragmentingSocketWrapper so that when SSLSocket performs
     *    startHandshake(), the outbound TLS ClientHello record is genuinely fragmented on the wire.
     * 3. Sends the custom HTTP/WebSocket payload over the established stream.
     * 4. Disables fragmentation after handshake so regular data transfer runs at full speed.
     */
    suspend fun establishFragmentedTlsTunnel(
        profile: TunnelProfile,
        vpnService: VpnService? = null
    ): Socket? = withContext(Dispatchers.IO) {
        var rawSocket: Socket? = null
        try {
            rawSocket = Socket()
            vpnService?.protect(rawSocket)
            rawSocket.tcpNoDelay = true
            rawSocket.keepAlive = true
            rawSocket.soTimeout = 10000
            rawSocket.connect(InetSocketAddress(profile.remoteIp, profile.remotePort), 5000)

            // Wrap rawSocket so SSLSocket's own ClientHello is split into chunks
            val fragmentingWrapper = FragmentingSocketWrapper(
                delegate = rawSocket,
                chunkSize = profile.fragmentChunkSize,
                jitterMs = profile.fragmentJitterMs
            )

            val factory = SSLSocketFactory.getDefault() as SSLSocketFactory
            val sslSocket = factory.createSocket(
                fragmentingWrapper,
                profile.targetSni,
                profile.remotePort,
                true
            ) as SSLSocket

            val sslParams = SSLParameters().apply {
                if (profile.targetSni.isNotBlank()) {
                    serverNames = listOf(SNIHostName(profile.targetSni))
                }
            }
            sslSocket.sslParameters = sslParams

            // During this call, FragmentedOutputStream intercepts and splits the actual ClientHello
            sslSocket.startHandshake()
            Log.i(TAG, "Fragmented TLS ClientHello handshake succeeded with SNI: ${profile.targetSni}")

            // Send custom HTTP/WebSocket upgrade headers (also fragmented)
            val payloadBytes = buildPayload(profile).toByteArray(StandardCharsets.UTF_8)
            sslSocket.outputStream.write(payloadBytes)
            sslSocket.outputStream.flush()

            // Turn off micro-fragmentation after handshake & payload so throughput isn't throttled
            fragmentingWrapper.fragmentedOut.fragmentationActive = false

            // Verify HTTP 101 / 200 handshake response from the server
            val buffer = ByteArray(1024)
            val bytesRead = sslSocket.inputStream.read(buffer)
            if (bytesRead > 0) {
                val response = String(buffer, 0, bytesRead, StandardCharsets.UTF_8)
                Log.d(TAG, "Server handshake response: ${response.lineSequence().firstOrNull()}")
                if (response.contains("101") || response.contains("200") || response.contains("Established", ignoreCase = true)) {
                    sslSocket.soTimeout = 0 // Reset timeout for persistent streaming
                    return@withContext sslSocket
                }
            }

            sslSocket.close()
            null
        } catch (e: Exception) {
            Log.e(TAG, "Failed to establish fragmented TLS tunnel: ${e.message}", e)
            try { rawSocket?.close() } catch (_: Exception) {}
            null
        }
    }
}
